import React, { useEffect, useMemo, useState } from "react";
import { Box, Button, Chip, Paper, Stack, Tab, Table, TableBody, TableCell, TableContainer, TableHead, TableRow, Tabs, Typography } from "@mui/material";
import OpenInNewIcon from "@mui/icons-material/OpenInNew";
import DownloadIcon from "@mui/icons-material/Download";
import { useArtifacts, useSection } from "../api/hooks";
import { EmptyState, SectionRenderer } from "../components/Sections/SectionRenderer";
import { FONT_MONO, PALETTE } from "../theme";

const REPORT_ORDER = ["reports/meridian_summary.html", "reports/meridian_health_card.html", "reports/meridian_optimization.html"];
const REPORT_LABEL: Record<string, string> = {
  "reports/meridian_summary.html": "Model summary",
  "reports/meridian_health_card.html": "Health card",
  "reports/meridian_optimization.html": "Budget optimisation",
};
const CATEGORY_ORDER = ["report", "data", "model", "meta", "input", "section"];

export const ReportsPage: React.FC<{ runId: string | null }> = ({ runId }) => {
  const { data: section, isLoading, error } = useSection(runId, "reports");
  const { data: artifactsData } = useArtifacts(runId);
  const artifacts = useMemo(() => artifactsData?.artifacts ?? [], [artifactsData]);

  // Only offer the Meridian reports this run actually produced
  const reports = useMemo(
    () => artifacts.filter((a) => a.path.startsWith("reports/") && a.path.endsWith(".html")).sort((a, b) => REPORT_ORDER.indexOf(a.path) - REPORT_ORDER.indexOf(b.path)),
    [artifacts]
  );
  const [reportPath, setReportPath] = useState<string | null>(null);
  useEffect(() => {
    if (!reports.some((r) => r.path === reportPath)) setReportPath(reports[0]?.path ?? null);
  }, [reports, reportPath]);
  const active = reports.find((r) => r.path === reportPath);

  const downloads = useMemo(
    () =>
      artifacts
        .filter((a) => a.category !== "section")
        .sort((a, b) => CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category) || a.path.localeCompare(b.path)),
    [artifacts]
  );

  return (
    <Box>
      <SectionRenderer section={section} isLoading={isLoading} error={error as Error | null} />

      {runId && (
        <Paper component="section" aria-labelledby="reports-title" sx={{ p: { xs: 2, md: 3 }, mb: 4 }}>
          <Stack direction={{ xs: "column", sm: "row" }} justifyContent="space-between" alignItems={{ xs: "flex-start", sm: "center" }} spacing={1.5} sx={{ mb: 2 }}>
            <Box>
              <Typography id="reports-title" variant="h2">
                Google Meridian's HTML reports
              </Typography>
              <Typography variant="body2">Generated by Meridian for this run and shown in a sandboxed frame.</Typography>
            </Box>
            {active && (
              <Button size="small" variant="outlined" endIcon={<OpenInNewIcon fontSize="small" />} href={active.url} target="_blank" rel="noopener">
                Open in a new tab
              </Button>
            )}
          </Stack>

          {reports.length === 0 ? (
            <EmptyState title="No Meridian reports yet">
              They are written when the Meridian stages finish (they are not produced for runs that skip Meridian).
            </EmptyState>
          ) : (
            <>
              <Tabs
                value={reportPath ?? false}
                onChange={(_, v) => setReportPath(v)}
                variant="scrollable"
                allowScrollButtonsMobile
                aria-label="Meridian reports"
                sx={{ mb: 2, borderBottom: `1px solid ${PALETTE.borderSubtle}` }}
              >
                {reports.map((r) => (
                  <Tab key={r.path} value={r.path} label={REPORT_LABEL[r.path] ?? r.filename} />
                ))}
              </Tabs>
              {active && (
                <Box sx={{ width: "100%", height: "min(760px, 80vh)", border: `1px solid ${PALETTE.borderSubtle}`, borderRadius: 1.5, backgroundColor: "#FFFFFF" }}>
                  <iframe
                    key={active.path}
                    title={`Meridian ${REPORT_LABEL[active.path] ?? active.filename}`}
                    src={active.url}
                    sandbox="allow-scripts"
                    loading="lazy"
                    style={{ width: "100%", height: "100%", border: "none", borderRadius: 10 }}
                  />
                </Box>
              )}
            </>
          )}
        </Paper>
      )}

      {downloads.length > 0 && (
        <Paper component="section" aria-labelledby="downloads-title" sx={{ p: { xs: 2, md: 3 } }}>
          <Typography id="downloads-title" variant="h3" component="h2" sx={{ mb: 2 }}>
            All files of this run ({downloads.length})
          </Typography>
          <TableContainer role="region" aria-labelledby="downloads-title" tabIndex={0} sx={{ maxHeight: 460, border: `1px solid ${PALETTE.borderSubtle}`, borderRadius: 1.5 }}>
            <Table size="small" stickyHeader>
              <TableHead>
                <TableRow>
                  <TableCell scope="col">File</TableCell>
                  <TableCell scope="col">Type</TableCell>
                  <TableCell scope="col">Path</TableCell>
                  <TableCell scope="col" align="right">
                    Download
                  </TableCell>
                </TableRow>
              </TableHead>
              <TableBody>
                {downloads.map((art) => (
                  <TableRow key={art.path} hover>
                    <TableCell component="th" scope="row" sx={{ fontWeight: 600 }}>
                      {art.filename}
                    </TableCell>
                    <TableCell>
                      <Chip size="small" label={art.category} />
                    </TableCell>
                    <TableCell sx={{ fontFamily: FONT_MONO, fontSize: "0.78rem", color: PALETTE.inkSecondary }}>{art.path}</TableCell>
                    <TableCell align="right">
                      <Button size="small" startIcon={<DownloadIcon fontSize="small" />} href={`${art.url}?download=true`} aria-label={`Download ${art.filename}`}>
                        Download
                      </Button>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </TableContainer>
        </Paper>
      )}
    </Box>
  );
};
